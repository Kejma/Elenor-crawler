def acquisition_bonuses(rarity, stats):
    budget = {"common": 0.0, "uncommon": 0.12, "rare": 0.24, "epic": 0.4, "legendary": 0.6}.get(rarity, 0.0)
    return {stat: budget / len(stats) for stat in stats}
